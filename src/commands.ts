import { escapeHtml } from './core/formatter.js';

/**
 * Единственный источник правды по командам бота. Знать о них хотят три места: роутинг в
 * bot.ts, меню Telegram (setMyCommands) и текст /help. Разъедутся — фича «бот подсказывает
 * команды» сломается ровно в том, ради чего сделана, поэтому список живёт здесь один.
 *
 * Хендлеры сюда не кладём: /help нужен этот список, а списку — хендлер /help, вышел бы
 * цикл импортов. Регистрация остаётся явной в bot.ts, а от рассинхрона страхует тест.
 */
export interface BotCommand {
  /** Имя без слэша. Telegram принимает только [a-z0-9_], до 32 символов. */
  command: string;
  /** Строка для меню у поля ввода. Обычный текст, до 256 символов. */
  description: string;
  /** Placeholder аргумента для /help, если команда его ждёт. */
  usage?: string;
  /** Абзац для /help; у самоочевидных команд не нужен. Разметку добавляет renderHelp. */
  details?: string;
}

// Порядок = порядок в меню Telegram. Сверху то, чем пользуются каждый день.
export const COMMANDS: BotCommand[] = [
  {
    command: 'summary',
    description: 'краткий пересказ статьи или видео',
    usage: '<ссылка>',
    details:
      'Верну краткий пересказ на русском прямо в чат. Объём подстраивается под источник: ' +
      'у короткой заметки это пара предложений, у часового видео — несколько смысловых блоков.',
  },
  {
    command: 'article',
    description: 'видео → полная статья .md-файлом',
    usage: '<ссылка>',
    details:
      'Разверну расшифровку видео в статью с заголовками и пришлю .md-файлом. Это не пересказ: ' +
      'содержание сохраняется целиком, убираю только рекламу и мусор устной речи. Длинное видео ' +
      'обрабатывается несколько минут, я показываю прогресс. Если ссылка не на видео — отдам ' +
      'текст страницы в .md сразу.',
  },
  { command: 'help', description: 'список команд и что они делают' },
  { command: 'start', description: 'краткое приветствие' },
];

// Главное, чего нет в списке команд: команда для пересказа не обязательна.
const FOOTER =
  'Ссылку можно прислать и просто сообщением, без команды — это то же самое, что /summary.';

/** Справка для /help: Telegram-HTML, готовый к отправке. */
export function renderHelp(): string {
  const blocks = COMMANDS.map((c) => {
    const args = c.usage ? ` ${escapeHtml(c.usage)}` : '';
    const head = `<b>/${c.command}${args}</b> — ${escapeHtml(c.description)}`;
    return c.details ? `${head}\n${escapeHtml(c.details)}` : head;
  });
  return ['<b>Что я умею</b>', ...blocks, FOOTER].join('\n\n');
}
